r.h2("Базовый предсказатель: decision stump")
r.text(
    "Бустинг строится поверх слабых классификаторов. В этой работе слабый "
    "предсказатель, decision stump (решающий пень), глубина 1: одна проверка "
    "вида x[j] <= t, и два листовых значения для левой и правой ветвей."
)
f_stump = r.formula(
    r"h(x) = c_L \cdot [x_j \leq t] + c_R \cdot [x_j > t]",
    where="j индекс признака, t порог, c_L и c_R листовые значения, [·] индикатор условия.",
)
r.text(
    f"Пень ({f_stump}) разбивает выборку на две части по признаку j с порогом t. "
    "При обучении на остатках (negative gradient log-loss) листовое значение оптимизирует squared error "
    "и получается как среднее остатков в листе:"
)
f_leaf = r.formula(
    r"c_L = \frac{1}{|S_L|}\sum_{i \in S_L} r_i,\quad c_R = \frac{1}{|S_R|}\sum_{i \in S_R} r_i",
    where="S_L и S_R подмножества объектов, попавших в левый и правый листы, r_i остаток объекта i.",
)
r.text(
    f"Листовые значения ({f_leaf}) это средние residuals по объектам в каждом листе. "
    "Поиск лучшего сплита перебирает все признаки в подвыборке и до 50 пороговых значений на каждый, "
    "расположенных по квантилям, минимизируя суммарный MSE по двум листьям. Это сильно ускоряет "
    "тренировку по сравнению с проверкой всех уникальных значений."
)

r.h2("Бинарный gradient boosting на log-loss")
r.text(
    "Бинарный классификатор минимизирует log-loss относительно сырого предсказания F(x). "
    "Сигмоида переводит F в вероятность класса 1:"
)
f_sigma = r.formula(
    r"\sigma(F) = \frac{1}{1 + e^{-F}}",
)
f_logloss = r.formula(
    r"L(y, F) = -\bigl[y \log \sigma(F) + (1 - y) \log (1 - \sigma(F))\bigr]",
    where="y ∈ {0, 1} истинная метка, F(x) сырое предсказание ансамбля.",
)
r.text(
    f"Сигмоида ({f_sigma}) и log-loss ({f_logloss}) задают целевую функцию, штрафующую уверенно "
    "неверные ответы. Алгоритм обучения последовательный. Стартовое значение, логарифм отношения шансов:"
)
f_init = r.formula(
    r"F_0 = \log \frac{p}{1 - p}",
    where="p доля положительных объектов в train, F_0 даёт калиброванное стартовое распределение вероятностей.",
)
r.text(
    f"Стартовое значение ({f_init}). На итерации m считается отрицательный градиент log-loss по F:"
)
f_resid = r.formula(
    r"r_i^{(m)} = -\frac{\partial L}{\partial F}\bigg|_{F = F_m(x_i)} = y_i - \sigma(F_m(x_i))",
)
r.text(
    f"Residuals ({f_resid}) показывают, насколько предсказанная вероятность отстаёт от истинной "
    "метки. На residuals обучается decision stump h_m, далее ансамбль сдвигается в сторону остатков:"
)
f_boost = r.formula(
    r"F_{m+1}(x) = F_m(x) + \nu \cdot h_m(x)",
    where="ν learning rate (0,1 в работе), h_m пень, обученный на residuals.",
)
r.text(
    f"Обновление ансамбля ({f_boost}) с малым ν сжимает шаг и работает как регуляризация: "
    "маленький ν при том же числе деревьев даёт более плавную сходимость и лучшее обобщение."
)
r.text(
    "На каждой итерации признаки для поиска сплита выбираются случайной "
    "подвыборкой размера max_features. Это снижает корреляцию между "
    "последовательными деревьями и работает как мягкая регуляризация."
)

r.h2("Расширение до 6 классов: One-vs-Rest")
r.text(
    "Для multi-class задачи строится 6 независимых бинарных бустингов, "
    "каждый различает свой класс против всех остальных. На предсказании берутся "
    "6 sigmoid-вероятностей и нормируются по сумме:"
)
f_ovr = r.formula(
    r"\hat{p}_k(x) = \frac{\sigma(F^{(k)}(x))}{\sum_{j=1}^{K} \sigma(F^{(j)}(x))},\quad \hat{y} = \mathrm{arg\,max}_{k}\; \hat{p}_k(x)",
    where="K число классов (6 в работе), F^{(k)} ансамбль для класса k против всех остальных, hat{p}_k нормированная вероятность.",
)
r.text(
    f"Нормировка ({f_ovr}) делает вектор вероятностей суммирующимся в единицу, "
    "argmax выбирает класс с максимальной нормированной вероятностью."
)
r.text(
    "OvR проще честного multinomial-лога и вписывается в готовый бинарный "
    "движок без переписывания. Цена, классификаторы не используют общую "
    "структуру задачи: каждый учится отдельно. Для HAR с относительно "
    "разнесёнными классами это не критично."
)

