r.h2("Гистограмма важности признаков (gain ratio)")
r.text(
    "Признаки оцениваются по gain ratio, нормированному приросту информации. "
    "Числовые признак X и таргет Y предварительно дискретизируются квантильным "
    "разбиением на k=10 интервалов: границы интервалов берутся как выборочные "
    "квантили уровня j/k для j=1,...,k-1. После дискретизации работаю с "
    "категориальными величинами."
)
r.text(
    "Базовая величина это энтропия Шеннона распределения таргета:"
)
f_entropy = r.formula(
    r"H(Y) = -\sum_{y \in \mathcal{Y}} p(y)\,\log_2 p(y)",
    where="p(y) доля наблюдений с категорией y таргета, Y множество категорий.",
)
r.text(
    f"Энтропия ({f_entropy}) измеряет неопределённость таргета в битах. "
    "Условная энтропия таргета при заданном признаке X считается как "
    "взвешенное среднее энтропий внутри групп, образованных значениями X:"
)
f_cond = r.formula(
    r"H(Y \mid X) = \sum_{v \in \mathcal{X}} \frac{|S_v|}{|S|}\, H(Y \mid X = v)",
    where="S_v подмножество наблюдений, в которых X=v, |S| общее число наблюдений.",
)
r.text(
    f"Разность ({f_entropy}) и ({f_cond}) даёт прирост информации (information gain):"
)
f_ig = r.formula(
    r"\mathrm{IG}(Y, X) = H(Y) - H(Y \mid X)",
)
r.text(
    f"Чем больше IG({f_ig}), тем сильнее знание X сокращает неопределённость Y. "
    "Проблема чистого IG в том, что он систематически завышает оценку для "
    "признаков с большим числом значений. Поэтому делю IG на собственную "
    "энтропию признака, она же split information:"
)
f_split = r.formula(
    r"\mathrm{SplitInfo}(X) = -\sum_{v \in \mathcal{X}} \frac{|S_v|}{|S|}\,\log_2 \frac{|S_v|}{|S|}",
)
r.text(
    f"Итоговая метрика, нормированный gain ratio, считается по формуле:"
)
f_gr = r.formula(
    r"\mathrm{GR}(Y, X) = \begin{cases} \dfrac{\mathrm{IG}(Y, X)}{\mathrm{SplitInfo}(X)}, & \mathrm{SplitInfo}(X) > 0 \\ 0, & \mathrm{SplitInfo}(X) = 0 \end{cases}",
)
r.text(
    f"Формула ({f_gr}) применяется для двух таргетов отдельно. Из-за того, что "
    "G_total заполнен в 23 строках, а КГФ в 93, для каждого таргета беру "
    "только строки, где он не пуст, и считаю gain ratio на своей подвыборке. "
    "Финальный балл признака это среднее по двум таргетам:"
)
f_mean = r.formula(
    r"\overline{\mathrm{GR}}(X) = \frac{1}{|\mathcal{T}|}\sum_{Y \in \mathcal{T}} \mathrm{GR}(Y, X)",
    where="T множество таргетов, в работе T={G_total, КГФ}.",
)
r.text(
    f"Среднее по ({f_mean}) исключает ситуацию, когда признаки получают высокий "
    "gain ratio за счёт совпадения паттерна пропусков с таргетом."
)
