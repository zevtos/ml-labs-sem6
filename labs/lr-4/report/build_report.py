LAB = Path(__file__).resolve().parent.parent
ASSETS = LAB / "assets"

r = Report(TitleConfig(
    work_type="Лабораторная работа",
    work_number="№4",
    topic='По дисциплине "Основы машинного обучения" на тему "Машины опорных векторов в задаче определения P300"',
    student_name="Пахомов В.В.",
    student_group="P3324",
    teacher_name="Солодкая М.А.",
    teacher_degree="к.т.н.",
    teacher_position="доцент",
    teacher_label="Проверила",
    year="2026",
))

r.toc()

# --- Введение -------------------------------------------------------------
r.h1("Введение")
r.text(
    "Цель работы: освоить машины опорных векторов на задаче определения "
    "потенциала P300 в данных EEG. Реализовать линейный SVM с нуля, обучить "
    "его на нескольких субъектах и оценить качество на отдельном испытуемом."
)
r.text(
    "Источник данных: MOABB, dataset BNCI2014-009, классическая P300-парадигма "
    "(speller). 10 субъектов, 18 EEG-каналов, частота 256 Гц. В работе берутся "
    "три субъекта (1, 2 и 3) для баланса между объёмом данных и временем загрузки."
)
r.text("Задачи работы:")
r.numbered([
    "Проанализировать данные, выделить эпохи и обосновать набор признаков.",
    "Обучить SVM в задаче P300 vs NonTarget, обосновать выбор типа машины и ядра.",
    "Посчитать accuracy, precision, recall и F1.",
    "Построить ROC-кривую и AUC.",
])

# --- Выполнение работы ----------------------------------------------------
r.h1("Выполнение работы")

r.h2("Описание данных и извлечение эпох")
r.text(
    "MOABB отдаёт сырые сессии в формате MNE Raw с аннотациями стимулов. Через "
    "mne.events_from_annotations извлекается таблица событий и словарь event_id с "
    "ключами Target и NonTarget. Для каждого стимула вырезается эпоха длиной "
    "0-800 мс от его начала, baseline-коррекция отключена."
)
r.text(
    "Тонкий момент с разбором event_id. Кажется естественным написать "
    "'Target' in key, чтобы выудить целевые коды. Это ловушка: подстрока 'Target' "
    "входит и в 'NonTarget', поэтому такая проверка одновременно ловит оба класса. "
    "В работе используется точное сравнение по нижнему регистру: "
    "k.strip().lower() == 'target' и аналогично для nontarget."
)
r.text(
    "После сбора по трём субъектам получается 5184 эпохи формы (5184, 18, 206), "
    "по 1728 на каждого. Распределение классов одинаково у всех: 288 Target и "
    "1440 NonTarget, естественный дисбаланс 1 к 5, типичный для P300-paradigm."
)

r.h2("Признаки")
r.text(
    "Для каждой эпохи вычисляется средняя амплитуда сигнала по 5 равным временным "
    "окнам длиной 160 мс: 0-160, 160-320, 320-480, 480-640, 640-800 мс. Окна "
    "охватывают весь временной интервал и попадают на пик P300, который у "
    "большинства субъектов виден около 300 мс после стимула."
)
r.text(
    "Признаков получается 18 каналов на 5 окон, итого 90 чисел на эпоху. "
    "Этот набор простой, не требует обучения экстрактора, и хорошо работает на "
    "линейных классификаторах для ERP-сигнала. Альтернативы вроде xDAWN или "
    "Riemannian features добавили бы качества, но в требования ЛР не входят."
)

r.h2("Subject-wise split")
r.text(
    "Случайное перемешивание эпох по всем субъектам приводит к завышенной "
    "оценке: эпохи одного человека попадают и в train, и в test, и классификатор "
    "учит индивидуальные особенности. Чтобы получить честные числа, train берётся "
    "по субъектам [1, 2], test по субъекту [3]. Это эмулирует ситуацию, когда "
    "BCI настраивается на новых пользователях по записям предшественников."
)
r.text(
    "Train: 3456 эпохи (576 Target, 2880 NonTarget). Поскольку отношение 1 к 5 "
    "сделает SVM ленивым (тривиальный классификатор всегда NonTarget даёт "
    "accuracy 0,83), проводится undersampling NonTarget до 2:1: остаётся 1152 "
    "NonTarget, 576 Target, всего 1728 объектов на тренировке."
)
r.text(
    "Test: 1728 эпох субъекта 3 без всякого undersampling, естественный "
    "дисбаланс сохраняется. Это правильно, для оценки в реальном применении "
    "класс Target всё равно встречается реже."
)

r.h2("Linear SVM (Pegasos)")
r.text(
    "Pegasos, стохастический субградиентный спуск на регуляризованной hinge-loss. "
    "Целевая функция:"
)
r.code(
    "L(w, b) = (lambda / 2) * ||w||^2 + max(0, 1 - y_i * (w . x_i + b))"
)
r.text(
    "На каждой итерации t берётся случайный объект i, learning rate "
    "eta = 1 / (lambda * t). Если margin = y_i * (w.x_i + b) < 1, "
    "обновление: w = (1 - eta * lambda) * w + eta * y_i * x_i, "
    "b = b + eta * y_i. Иначе только сжатие w на (1 - eta * lambda)."
)
r.text(
    "Параметры: C = 1, отсюда lambda = 1, max_iter = 3000, random_state = 42. "
    "Тренировка занимает примерно 7 миллисекунд (90 признаков, 1728 объектов "
    "в train). Метки переводятся из {0, 1} в {-1, +1} для совместимости с "
    "формулой hinge."
)
r.text(
    "Выбор линейного ядра обоснован двумя соображениями. ERP-разделение "
    "Target/NonTarget описывается линейной комбинацией амплитуд, в литературе "
    "это давно показано (LDA, sLDA на P300 работают сравнимо с RBF). При 90 "
    "признаках и 1728 объектов нелинейные ядра легко переобучаются и теряют "
    "обобщение между субъектами."
)
r.figure(
    str(ASSETS / "training_loss.png"),
    "Кривая обучения SVM, hinge + регуляризация по итерациям",
)
r.text(
    "Loss падает с 0,56 до плато около 0,38 за первые 1000 итераций. Дальше "
    "колебания около плато, типичное поведение стохастического спуска: "
    "обновления зависят от случайного объекта, поэтому идеально гладкой "
    "сходимости не получается."
)

r.h2("Метрики качества")
r.text(
    "На тесте subject 3 (1728 эпох, естественный 1:5) получены следующие числа. "
    "Все агрегаты, precision, recall и F1, посчитаны как macro-средние, чтобы "
    "не маскировать качество на минорном классе Target."
)
r.table(
    [
        ["Метрика", "Значение"],
        ["Accuracy", "0,977"],
        ["Precision (macro)", "0,963"],
        ["Recall (macro)", "0,953"],
        ["F1 (macro)", "0,958"],
        ["AUC", "0,995"],
    ],
    "Метрики SVM на тестовом субъекте",
)
r.figure(
    str(ASSETS / "confusion_matrix.png"),
    "Матрица ошибок на тестовом субъекте",
)
r.text(
    "Из матрицы ошибок: TN = 1424, FP = 16, FN = 24, TP = 264. На целевом "
    "классе recall = 264 / 288 = 0,917, precision = 264 / 280 = 0,943. "
    "Из 288 истинных Target пропущено 24 эпохи (8 процентов), при этом ложных "
    "срабатываний всего 16 на 1440 NonTarget (1,1 процента)."
)
r.figure(
    str(ASSETS / "roc_curve.png"),
    "ROC-кривая SVM, AUC = 0,995",
)
r.text(
    "ROC-кривая практически прижата к левому верхнему углу: при FPR около 5 "
    "процентов TPR уже выше 95. AUC = 0,995 говорит о почти идеальном порядковом "
    "разделении классов в decision-function. На практике это значит, что выбор "
    "порога между классами сводится к тонкой настройке trade-off между "
    "пропусками и ложными срабатываниями."
)

# --- Заключение -----------------------------------------------------------
r.h1("Заключение")
r.numbered([
    "Linear SVM с Pegasos-обновлением реализован с нуля на numpy: hinge loss "
    "с регуляризацией по lambda = 1/C, learning rate 1 / (lambda * t), 3000 "
    "стохастических итераций. Тренировка занимает около 7 миллисекунд.",
    "Признаки, средние амплитуды по 5 временным окнам и 18 каналам, всего 90 "
    "чисел на эпоху. Простой набор, ловящий пик P300 без обучения экстрактора.",
    "Subject-wise split (train на S1, S2, test на S3) даёт честную оценку "
    "обобщения на нового пользователя. В train применён undersampling до 2:1, "
    "в test сохранён естественный дисбаланс 1 к 5.",
    "На тесте subject 3 получены: Accuracy = 0,977, Precision = 0,963, "
    "Recall = 0,953, F1 = 0,958, AUC = 0,995. Линейная граница между Target и "
    "NonTarget хорошо переносится с одних людей на других.",
    "Линейное ядро обосновано высокой размерностью признаков и характером ERP: "
    "нелинейные ядра при 90 признаках и 1728 train-объектов легко переобучаются.",
])

